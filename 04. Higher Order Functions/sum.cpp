// рекурсивна функция, която намира сумата от елементите на масив;
// изпълнението на рекурсивните извиквания се явява частен случай
// на изпълнението на дясно свиване на масив (foldr)
int sum(int *arr, int i, int n) {
  if (i >= n)
    return 0;

  return arr[i] + sum(arr, i+1, n);
}

